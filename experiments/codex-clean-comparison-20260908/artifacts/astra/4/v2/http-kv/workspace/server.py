#!/usr/bin/env python3
"""Persistent, dependency-free HTTP key-value service."""

import argparse
import json
import math
import os
from pathlib import Path
import re
import signal
import sys
import tempfile
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import unquote_to_bytes, urlsplit

MAX_BODY = 1024 * 1024


def reject_constant(value):
    raise ValueError(f"Invalid JSON constant: {value}")


def decode_json(data):
    return json.loads(data, parse_constant=reject_constant)


def encode_json(value):
    return json.dumps(value, ensure_ascii=True, allow_nan=False, separators=(",", ":")).encode("utf-8")


def valid_key(key):
    if not isinstance(key, str) or not key or "/" in key:
        return False
    try:
        key.encode("utf-8")
    except UnicodeError:
        return False
    return True


class Store:
    def __init__(self, path):
        self.path = Path(path)
        self.lock = threading.Lock()
        self.entries = {}
        if self.path.exists():
            document = decode_json(self.path.read_text(encoding="utf-8"))
            if not isinstance(document, dict) or document.get("version") != 1 or not isinstance(document.get("entries"), dict):
                raise ValueError("Invalid persistence file")
            for key, entry in document["entries"].items():
                if not valid_key(key) or not isinstance(entry, dict) or set(entry) != {"value", "expires_at"}:
                    raise ValueError("Invalid persisted entry")
                expires = entry["expires_at"]
                if expires is not None and (type(expires) not in (int, float) or not math.isfinite(expires)):
                    raise ValueError("Invalid persisted expiration")
            encode_json(document)  # Also reject numbers that overflowed JSON parsing.
            self.entries = document["entries"]
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.save(self.live())

    def live(self):
        now = time.time()
        return {key: entry for key, entry in self.entries.items()
                if entry["expires_at"] is None or entry["expires_at"] > now}

    def save(self, entries):
        data = encode_json({"version": 1, "entries": entries})
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=self.path.parent, prefix=f".{self.path.name}.", delete=False) as output:
                temporary = output.name
                output.write(data)
                output.flush()
                os.fsync(output.fileno())
            os.replace(temporary, self.path)
            temporary = None
            self.entries = entries
        finally:
            if temporary is not None:
                os.unlink(temporary)

    def perform(self, method, key=None, value=None, ttl=None):
        with self.lock:
            entries = self.live()
            present = key in entries
            changed = len(entries) != len(self.entries)
            if method == "PUT":
                entries[key] = {"value": value, "expires_at": None if ttl is None else time.time() + ttl}
                self.save(entries)
                return (200 if present else 201), {"key": key, "value": value}
            if method == "DELETE" and present:
                del entries[key]
                changed = True
            if changed:
                self.save(entries)
            if method == "KEYS":
                return 200, {"keys": sorted(entries)}
            if not present:
                return 404, {"error": "Key not found"}
            if method == "DELETE":
                return 204, None
            return 200, {"key": key, "value": entries[key]["value"]}


class APIError(Exception):
    def __init__(self, status, message):
        self.status, self.message = status, message


class Handler(BaseHTTPRequestHandler):
    # Close each connection so rejected or unused bodies cannot desynchronize it.
    protocol_version = "HTTP/1.0"

    def send_json(self, status, body):
        data = b"" if body is None else encode_json(body)
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(data)

    def send_error(self, code, message=None, explain=None):
        # Include errors generated by the HTTP parser and unsupported methods.
        self.close_connection = True
        self.send_json(code, {"error": message or self.responses.get(code, ("Request error",))[0]})

    def __getattr__(self, name):
        if name.startswith("do_"):
            return self.unsupported
        raise AttributeError(name)

    def unsupported(self):
        self.send_error(405, "Method not allowed")

    def body_length(self):
        if self.headers.get("Transfer-Encoding") is not None:
            raise APIError(400, "Transfer-Encoding is not supported")
        lengths = self.headers.get_all("Content-Length", [])
        if not lengths:
            return 0
        if len(lengths) != 1 or not re.fullmatch(r"[0-9]+", lengths[0].strip()):
            raise APIError(400, "Invalid Content-Length")
        text = lengths[0].strip().lstrip("0") or "0"
        if len(text) > 7 or int(text) > MAX_BODY:
            raise APIError(413, "Request body exceeds 1 MiB")
        return int(text)

    def route(self):
        try:
            path = urlsplit(self.path).path
        except ValueError:
            raise APIError(400, "Invalid URL")
        if path in ("/health", "/v1/keys"):
            return path, None
        prefix = "/v1/kv/"
        if not path.startswith(prefix):
            raise APIError(404, "Unknown route")
        raw = path[len(prefix):]
        if re.search(r"%(?![0-9A-Fa-f]{2})", raw):
            raise APIError(400, "Invalid key encoding")
        try:
            key = unquote_to_bytes(raw).decode("utf-8", errors="strict")
        except UnicodeError:
            raise APIError(400, "Key must be UTF-8")
        if not valid_key(key):
            raise APIError(400, "Key must be nonempty and contain no slash")
        return "kv", key

    def handle_api(self):
        try:
            length = self.body_length()
            route, key = self.route()
            if route != "kv":
                if self.command != "GET":
                    raise APIError(405, "Method not allowed")
                if route == "/health":
                    status, body = 200, {"status": "ok"}
                else:
                    status, body = self.server.store.perform("KEYS")
            elif self.command == "PUT":
                data = self.rfile.read(length)
                if len(data) != length:
                    raise APIError(400, "Incomplete request body")
                try:
                    document = decode_json(data.decode("utf-8"))
                    encode_json(document)
                except (ValueError, UnicodeError, OverflowError, RecursionError):
                    raise APIError(400, "Malformed JSON")
                if not isinstance(document, dict) or "value" not in document or set(document) - {"value", "ttl_seconds"}:
                    raise APIError(400, "Expected value and optional ttl_seconds")
                ttl = document.get("ttl_seconds")
                if "ttl_seconds" in document:
                    try:
                        valid = type(ttl) in (int, float) and math.isfinite(ttl) and ttl > 0 and math.isfinite(time.time() + ttl)
                    except OverflowError:
                        valid = False
                    if not valid:
                        raise APIError(400, "ttl_seconds must be finite and greater than zero")
                status, body = self.server.store.perform("PUT", key, document["value"], ttl)
            else:
                status, body = self.server.store.perform(self.command, key)
            self.send_json(status, body)
        except APIError as error:
            self.send_error(error.status, error.message)
        except (TimeoutError, ConnectionError):
            self.close_connection = True
        except Exception as error:
            self.log_error("Request failed: %s", error)
            self.send_error(500, "Internal server error")

    do_GET = handle_api
    do_PUT = handle_api
    do_DELETE = handle_api


class Server(ThreadingHTTPServer):
    daemon_threads = False
    block_on_close = True

    def get_request(self):
        connection, address = super().get_request()
        connection.settimeout(5)
        return connection, address


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    parser.add_argument("--data", required=True, type=Path)
    args = parser.parse_args()
    try:
        store = Store(args.data)
        server = Server((args.host, args.port), Handler)
    except (OSError, ValueError, OverflowError, RecursionError) as error:
        print(f"Startup failed: {error}", file=sys.stderr)
        return 1
    server.store = store
    stopping = threading.Event()

    def stop(signum, frame):
        if not stopping.is_set():
            stopping.set()
            threading.Thread(target=server.shutdown, daemon=True).start()

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    print(f"LISTENING {server.server_port}", flush=True)
    try:
        server.serve_forever(poll_interval=0.1)
    finally:
        server.server_close()  # Join active requests before writing the final snapshot.
        with store.lock:
            store.save(store.live())
    return 0


if __name__ == "__main__":
    sys.exit(main())
